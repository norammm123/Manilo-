class PinyinIME:
    """拼音输入法引擎"""

    def __init__(self, vocabulary=None):
        """
        vocabulary: dict, pinyin → [汉字列表], 按常用度排序
                    不传则使用内置基础词典
        """
        self.vocab = vocabulary or _BUILTIN_DICT

    def split_syllables(self, letters):
        """贪心最长匹配: 每个位置取最长有效音节, "nihao" → (["ni", "hao"], 5)
        返回 (音节列表, 消耗的输入字符数, 含跳过的无效字符)
        注意: 必须取"最长"而非字母序第一个, 否则 "hao" 会被 "ha" 抢先切走
        """
        syllables = []
        pos = 0
        while pos < len(letters):
            matched = None
            for syl in PINYIN_SYLLABLES:
                if letters.startswith(syl, pos) and \
                        (matched is None or len(syl) > len(matched)):
                    matched = syl
            if matched:
                syllables.append(matched)
                pos += len(matched)
            else:
                # 未匹配: 跳过当前字符, 避免死循环
                pos += 1
        return syllables, pos  # pos = 总消耗字符数

    def convert(self, syllables):
        """音节列表 → 汉字候选列表"""
        result = []
        for syl in syllables:
            if syl in self.vocab:
                result.append(self.vocab[syl])
            else:
                result.append([syl])  # 未知音节保留拼音
        return result

    def top1(self, syllables):
        """取每个音节最常用汉字, 未收录的音节跳过 (不阻塞整句)"""
        chars = []
        for syl in syllables:
            if syl in self.vocab and self.vocab[syl]:
                chars.append(self.vocab[syl][0])
        if not chars:
            return ""
        result = ''.join(chars)
        if result.isascii():
            return ""
        return result

    def process(self, letters):
        """完整管道: 字母序列 → 汉字字符串 (top-1)
        返回 (chinese, syllables, consumed_len)
        consumed_len: 总消耗的输入字符数 (含跳过的无效字符)
        """
        syllables, consumed_len = self.split_syllables(letters)
        return self.top1(syllables), syllables, consumed_len

    def can_extend_last(self, letters):
        """末尾音节是否可能续写 (停顿提交的防半字判定)
        "niha"  → ["ni","ha"], "ha" 可续写为 hao/hai/han... → True (可能还在输入)
        "nihao" → ["ni","hao"], "hao" 无可续写              → False (音节完整, 可提交)
        "mama"  → ["ma","ma"], "ma" 可续写                  → True (停顿够久仍会提交)
        """
        syllables, consumed = self.split_syllables(letters)
        if consumed < len(letters):
            return True  # 有未消耗的尾巴(无效/未完成字母), 视为可能还在输入
        if not syllables:
            return False
        last = syllables[-1]
        return any(s.startswith(last) and len(s) > len(last)
                   for s in PINYIN_SYLLABLES)


